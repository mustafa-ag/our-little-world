// Simplified but recognisable coastlines (lat, lng). Equirectangular world map.

export type Ring = [number, number][]; // [lat, lng]

export interface LandPoly {
  color: number;
  rings: Ring[];
}

export interface PlaceName {
  name: string;
  lat: number;
  lng: number;
  kind: "continent" | "country";
}

/** Famous spots you can see but not visit yet. */
export interface LockedCity {
  name: string;
  lat: number;
  lng: number;
}

export const MAP_W = 2400;
export const MAP_H = 1200;

export function geoToMap(lat: number, lng: number) {
  return {
    x: ((lng + 180) / 360) * MAP_W,
    y: ((90 - lat) / 180) * MAP_H,
  };
}

